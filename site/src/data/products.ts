/* -------------------------------------------------------------------------
   Lookups. Built once at module load — this file is imported by server code on
   every checkout, so the maps matter.
   ------------------------------------------------------------------------- */

export const productsBySlug = new Map(products.map((p) => [p.slug, p]));
export const productsById = new Map(products.map((p) => [p.id, p]));

export function getProduct(slug: string): Product | undefined {
  return productsBySlug.get(slug);
}

/** SKU format: `<productId>` — the size and colourway ride alongside on the line. */
export function getProductBySku(sku: string) {
  return productsById.get(sku);
}

export function getProductsByCategory(category: string): Product[] {
  return products.filter((p) => p.category === category);
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  const sameSub = products.filter(
    (p) => p.id !== product.id && p.category === product.category && p.subcategory === product.subcategory,
  );
  const sameCat = products.filter(
    (p) => p.id !== product.id && p.category === product.category && p.subcategory !== product.subcategory,
  );
  return [...sameSub, ...sameCat].slice(0, limit);
}

export function getBadgedProducts(badge: string, limit = 8): Product[] {
  return products.filter((p) => p.badges.includes(badge as never)).slice(0, limit);
}
